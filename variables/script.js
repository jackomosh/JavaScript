// a variable is a named storage of data
// variable names must contain only letters, digits and symbols
// the first character of a variable name cannot be a digit
// hyphens are not allowed in variable names
// variable names are case sensitive

let message;

message = "Hello"

alert(message);

// multiple declaration in one line

let username = "Jack"; let age = 25; let year = 2000;

alert(username);
alert(age);
alert(year);

// multiline var naming

